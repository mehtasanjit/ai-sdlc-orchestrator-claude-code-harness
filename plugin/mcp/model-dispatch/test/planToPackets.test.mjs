/**
 * plan-to-packets.mjs --spec: the accepted change spec, checked as a whole (greenfield's finalize rules), rendered to
 * change_plan.md for Gate 2 and the reviewers, and turned into packets.json by code: one packet per unit, inputs as
 * paths, edits at the planned sites with the file's exact text, typed checks with their own write forms. Offline, $0.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SCRIPTS = join(HERE, "..", "..", "..", "scripts");
const { finalize, main } = await import(join(SCRIPTS, "plan-to-packets.mjs"));
const { quotePath, editAnswerLines } = await import(join(SCRIPTS, "lib", "change-spec.mjs"));
const { HEADER, UNITS, project } = await import(join(HERE, "fixtures", "change-spec.mjs"));
const { applySearchReplace } = await import(join(HERE, "..", "dist", "apply.js"));
const { renderRepairInstruction } = await import(join(HERE, "..", "dist", "executor", "brief.js"));
const { markSharedInputs } = await import(join(HERE, "..", "dist", "batch.js"));

const run = (root, extra = {}) => finalize({ projectRoot: root, runId: "r1", intent: "feature-extend", ...extra });
const read = (root, f) => readFileSync(join(root, ".sdlc", "runs", "r1", f), "utf8");

async function accepted(p, units = UNITS, header = HEADER) {
  assert.equal((await p.check("header.json", header)).ok, true);
  const u = await p.check("units-001.json", units);
  assert.equal(u.ok, true, u.lines.join("\n"));
}

test("the builder's whole-file bound is the server's (apply.ts MAX_SLICE_BYTES)", async () => {
  const { MAX_SLICE_BYTES: server } = await import(join(HERE, "..", "dist", "apply.js"));
  const { MAX_SLICE_BYTES: builder } = await import(join(SCRIPTS, "plan-to-packets.mjs"));
  assert.equal(builder, server);
});

test("packets from the spec: one per unit, routed by phase alone, inputs as paths, typed checks with their own write forms", async () => {
  const p = project();
  try {
    await accepted(p);
    const r = await run(p.root);
    assert.equal(r.code, 0, r.err.join("\n"));
    const [b, a] = JSON.parse(read(p.root, "packets.json"));
    assert.equal(b.id, "tp_codegen_U01");
    assert.equal(b.task_type, "", "no task type: a file is routed by its stage, as greenfield's are");
    assert.equal(b.subtype, "new_file_add");
    assert.deepEqual(b.inputs.map((i) => i.path), [".sdlc/runs/r1/briefs/shared.md", ".sdlc/runs/r1/briefs/U01.md", "src/x.ts"]);
    // Greenfield's caching: only the block every packet shares is marked stable (cached); a packet's own brief goes
    // after it, uncached, since a cached block no other packet reads is a cache write, not a saving.
    assert.deepEqual(b.inputs.map((i) => /\bstable\b/.test(i.reason)), [true, false, false]);
    assert.deepEqual(b.apply.checks, [{ id: "lint", run: "npx biome check '{path}'", fix: "npx biome check --write '{path}'" }], "the unit's own checks only: no check tied to one language");
    assert.equal(b.apply.baseline_from, "src/x.ts", "a new file's checks are tried on its style file first");
    assert.equal(b.apply.verify_timeout_sec, 45, "each check may run as long as the plan says its slowest check takes");
    assert.equal(b.budget.maxOutputTokens, 8192, "greenfield's fallback when a model declares no output limit");
    assert.equal(b.apply.mode, "content");
    assert.equal(a.id, "tp_codegen_U02");
    assert.deepEqual(a.depends_on, ["tp_codegen_U01"]);
    assert.equal(a.subtype, "existing_file_edit");
    assert.equal(a.apply.mode, "edits");
    assert.equal(a.apply.baseline_from, undefined, "an edit's checks are tried on the file itself");
    assert.deepEqual(a.inputs.map((i) => [i.path, i.reason]).at(-1), ["src/a.ts", "current text"]);
    assert.match(a.instruction, /- S1: insert after line 1 \(line 1 reads `import \{ x \} from "\.\/x";`\) — import b/);
    assert.match(a.instruction, /"edits": \[\{"search": "<text copied exactly from the current text>", "replace": "<its replacement>"\}\]/);
    assert.deepEqual(a.verify_deferred, ["npx tsc --noEmit"], "the project checks run once, after the last file");
    assert.equal(b.verify_deferred, undefined);
    assert.match(r.text, /2 packets \(2 codegen, 0 tests, 0 docs, 0 tooling; 1 edit lists; 1 end-of-run checks\)/);
  } finally { p.done(); }
});

test("change_plan.md and the briefs are rendered by code; the shared brief is the same bytes for every packet, so a batch marks it shared", async () => {
  const p = project();
  try {
    await accepted(p);
    await run(p.root);
    const plan = read(p.root, "change_plan.md");
    assert.match(plan, /^# Change plan — r1/);
    assert.match(plan, /do not edit this file/);
    assert.match(plan, /\| U02 \| edit \| codegen \| `src\/a\.ts` \| U01 \|/);
    assert.match(plan, /- S1: insert after line 1 \(line 1 reads `import \{ x \} from "\.\/x";`\) — import b/);
    assert.match(plan, /- lint \(each file\): `npx biome check \{path\}`; fix: `npx biome check --write \{path\}`/);
    const shared = read(p.root, "briefs/shared.md");
    assert.match(shared, /- `src\/b\.ts` \(U01, create\) — import: `import \{ b \} from "\.\/b";`/);
    assert.match(read(p.root, "briefs/U02.md"), /## Files it depends on[\s\S]*U01 — create `src\/b\.ts`/);
    const marked = markSharedInputs(JSON.parse(read(p.root, "packets.json")));
    for (const pk of marked) assert.deepEqual(pk.inputs.filter((i) => i.shared).map((i) => i.path), [".sdlc/runs/r1/briefs/shared.md"]);
  } finally { p.done(); }
});

test("finalize refuses a spec that no longer matches the files, or leaves a requirement uncovered", async () => {
  const p = project();
  try {
    await accepted(p);
    writeFileSync(join(p.root, ".sdlc", "runs", "r1", "requirements.md"), "- FR-1 b\n- FR-2 c\n- AC-1 b is 2\n");
    const cover = await run(p.root);
    assert.equal(cover.code, 1);
    assert.match(cover.err.join("\n"), /no unit covers FR-2, AC-1 \(requirements\.md\)/);
    writeFileSync(join(p.root, ".sdlc", "runs", "r1", "requirements.md"), "- FR-1 b\n");
    writeFileSync(join(p.root, "src", "a.ts"), "// someone edited this\n");
    const changed = await run(p.root);
    assert.equal(changed.code, 1);
    assert.match(changed.err.join("\n"), /src\/a\.ts changed since units-001\.json was accepted/);
  } finally { p.done(); }
});

test("finalize checks the units as a whole: a re-sent section that drops a unit others depend on is refused", async () => {
  const p = project();
  try {
    assert.equal((await p.check("header.json", HEADER)).ok, true);
    assert.equal((await p.check("units-001.json", [UNITS[0]])).ok, true);
    assert.equal((await p.check("units-002.json", [UNITS[1]])).ok, true);
    assert.equal((await p.check("units-001.json", [{ ...UNITS[0], id: "U03" }])).ok, true, "units-001 re-sent with another id");
    const r = await run(p.root);
    assert.equal(r.code, 1);
    assert.match(r.err.join("\n"), /U02\.depends_on: U01 is not an earlier unit/);
    const none = project();
    try {
      const empty = await finalize({ projectRoot: none.root, runId: "r1", intent: "feature-new" });
      assert.match(empty.err.join("\n"), /no header section was accepted[\s\S]*no units section was accepted/);
    } finally { none.done(); }
  } finally { p.done(); }
});

test("a tooling unit is a shell step for the orchestrator, and the units after it wait for it", async () => {
  const p = project();
  try {
    const tool = { id: "U01", path: "package.json", action: "tooling", phase: "codegen", behaviour: "Adds the zod dependency.", run: "pnpm add zod", depends_on: [] };
    writeFileSync(join(p.root, "package.json"), "{}\n");
    await accepted(p, [tool, { ...UNITS[1], depends_on: ["U01"] }]);
    const r = await run(p.root);
    assert.equal(r.code, 0, r.err.join("\n"));
    const [t, a] = JSON.parse(read(p.root, "packets.json"));
    assert.equal(t.id, "tooling_U01");
    assert.equal(t.apply, undefined, "the server never runs it");
    assert.match(t.instruction, /Orchestrator shell step, no model \(unit U01\): run `pnpm add zod`/);
    assert.deepEqual(a.depends_on, ["tooling_U01"]);
  } finally { p.done(); }
});

// One edit contract for both flows: the brownfield instruction ends with greenfield's own answer wording
// (executor/brief.ts renderRepairInstruction), so a typist is asked the same way in either, and the server applies the
// answer with greenfield's applier.
test("an edit packet asks for greenfield's exact edits in greenfield's own words", () => {
  const gUnit = { id: "U01", path: "src/a.ts", phase: "codegen", behaviour: "b", exports: [], import_line: "", depends_on: [], style_from: { reason: "r" }, covers: [], tests: [], approx_lines: 1 };
  const greenfield = renderRepairInstruction({ units: [gUnit] }, { path: "src/a.ts", unit: gUnit }, ["x"]).split("\n");
  const tail = greenfield.slice(greenfield.indexOf("The file's current text is under Inputs, marked \"current text\"; your edits apply to exactly that text."));
  assert.deepEqual(editAnswerLines("src/a.ts"), tail);
  const r = applySearchReplace("a\r\nb\r\n", { path: "src/a.ts", edits: [{ search: "a\nb", replace: "a\nx\nb" }] });
  assert.equal(r.content, "a\r\nx\r\nb\r\n", "an answer to that instruction applies to a CRLF file, keeping its ending");
});

test("{path} is single-quoted whatever the architect wrote, as the server puts it into a shell and paths carry $", () => {
  assert.equal(quotePath("biome check {path}"), "biome check '{path}'");
  assert.equal(quotePath('biome check "{path}"'), "biome check '{path}'");
  assert.equal(quotePath("biome check '{path}' && x {path}"), "biome check '{path}' && x '{path}'");
});

test("an edited file over the server's bound on one input is still sent whole, in consecutive parts", async () => {
  const p = project();
  try {
    const big = Array.from({ length: 30000 }, (_, i) => `const v${i} = ${i};`).join("\n") + "\n";
    writeFileSync(join(p.root, "src", "big.ts"), big);
    const unit = { id: "U01", path: "src/big.ts", action: "edit", phase: "codegen", behaviour: "b", sites: [{ id: "S1", at: "replace", from: 100, to: 100, first_line: "const v99 = 99;", rule: "r" }], depends_on: [] };
    await accepted(p, [unit]);
    await run(p.root);
    const [pk] = JSON.parse(read(p.root, "packets.json"));
    const parts = pk.inputs.filter((i) => i.path === "src/big.ts");
    assert.ok(parts.length >= 2, "more than one part");
    assert.equal(parts[0].lines[0], 1);
    for (let i = 1; i < parts.length; i++) assert.equal(parts[i].lines[0], parts[i - 1].lines[1] + 1, "no line left out");
    assert.equal(parts.at(-1).lines[1], 30001, "to the last line");
    assert.match(parts[0].reason, /current text: part 1 of \d+/);
  } finally { p.done(); }
});

